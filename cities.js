// Get a weighted random city for a given ISO2 code
function getPulseCity(iso2) {
  const cities = CITY_PULSES[iso2]
  if (!cities || cities.length === 0) return null
  const totalWeight = cities.reduce((s, c) => s + c[2], 0)
  let r = Math.random() * totalWeight
  for (const city of cities) {
    r -= city[2]
    if (r <= 0) {
      const spread = Math.min(city[2] * 0.008, 0.06)
      return {
        lat: city[0] + (Math.random() - 0.5) * spread,
        lng: city[1] + (Math.random() - 0.5) * spread
      }
    }
  }
  const city = cities[0]
  const spread = Math.min(city[2] * 0.008, 0.06)
  return {
    lat: city[0] + (Math.random() - 0.5) * spread,
    lng: city[1] + (Math.random() - 0.5) * spread
  }
}
